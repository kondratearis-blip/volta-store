// русская. {name} — подстановки: tx('Заказ № {n}', { n: 12 }). Тексты на кыргызском — specs/018-mini-app-v1/ky-texts.md,
// ПРОВЕРИТЬ НОСИТЕЛЮ ЯЗЫКА. Курьер, панель и экран кухни — только русский.
const KEY = 'kokoro.lang';
export const LANGS = ['ru', 'ky'];

function readLang() {
  try { return localStorage.getItem(KEY) === 'ky' ? 'ky' : 'ru'; } catch { return 'ru'; }
}
let current = readLang();
const listeners = new Set();

/** Текущий язык: 'ru' | 'ky' */
export const lang = () => current;

/** Сменить язык: запоминается на телефоне, <html lang>, разметка с [data-i18n] и подписчики onLang */
export function setLang(next) {
  const value = next === 'ky' ? 'ky' : 'ru';
  if (value === current) return;
  current = value;
  try { localStorage.setItem(KEY, value); } catch { /* приватный режим */ }
  document.documentElement.lang = value;
  applyI18n(document);
  listeners.forEach((fn) => { try { fn(value); } catch (err) { console.error(err); } });
}

/** Подписка на смену языка → функция отписки */
export const onLang = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };

/** Перевод русской строки (+ подстановки {name}) */
export function tx(ru, vars) {
  const key = String(ru ?? '');
  let text = current === 'ky' ? (KY[key] ?? key) : key;
  if (vars) text = text.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m));
  return text;
}

/**
 * Перевести разметку: [data-i18n] — текст элемента (только «листья» без вложенных тегов), [data-i18n-attr="placeholder,
 * aria-label"] — атрибуты. Русский оригинал хранится в data-ru / data-ru-<атрибут>, поэтому переключение туда-обратно
 * не накапливает ошибок. Пробелы по краям сохраняются
 */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    if (el.dataset.ru === undefined) el.dataset.ru = el.textContent;
    const ru = el.dataset.ru;
    const [, lead, core, tail] = /^(\s*)([\s\S]*?)(\s*)$/.exec(ru);
    el.textContent = lead + tx(core) + tail;
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const name of el.dataset.i18nAttr.split(',').map((s) => s.trim()).filter(Boolean)) {
      const store = `ru${name.replace(/(^|-)(\w)/g, (m, d, c) => c.toUpperCase())}`;
      if (el.dataset[store] === undefined) el.dataset[store] = el.getAttribute(name) ?? '';
      el.setAttribute(name, tx(el.dataset[store]));
    }
  });
}

/** Время ожидания по-кыргызски: 45 → «45 мүнөт», 60 → «1 саат», 90 → «1,5 саат», 100 → «1 саат 40 мүнөт» */
export function waitLabelKy(minutes) {
  const m = Math.round(Number(minutes));
  if (m < 60) return `${m} мүнөт`;
  const h = Math.floor(m / 60), rest = m % 60;
  if (rest === 0) return `${h} саат`;
  if (rest === 30) return `${h},5 саат`;
  return `${h} саат ${rest} мүнөт`;
}
/** Заказы по-кыргызски: у числа нет форм — «3 буйрутма» */
export const ordersLabelKy = (n) => `${n} буйрутма`;
/** «N мин назад» по-кыргызски (как maps.js → ago) */
export function agoKy(iso, now = Date.now()) {
  const min = Math.max(0, Math.round((now - new Date(iso).getTime()) / 60_000));
  if (min < 1) return 'азыр эле';
  if (min < 60) return `${min} мүн мурун`;
  return `${Math.round(min / 60)} саат мурун`;
}
